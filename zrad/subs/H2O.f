     &     0.86d0, 0.70d0, 0.63d0, 0.58d0, 0.55d0, 0.53d0, 
     &     0.93d0, 0.72d0, 0.66d0, 0.61d0, 0.57d0, 0.55d0, 
     &     0.87d0, 0.73d0, 0.67d0, 0.62d0, 0.59d0, 0.56/
c
      real*8 :: aL0bp(1:6)
      data aL0bp/27.01d0, 25.73d0, 25.24d0,
     &     24.75d0, 24.38d0, 24.22d0/
